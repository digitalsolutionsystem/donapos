/**
 * Render elemen SVG icon tunggal dengan gaya Lucide
 * @param {string} name Nama icon dari registry ICONS
 * @param {string} className Class tambahan opsional (e.g. 'icon-lg text-pri')
 * @param {number|string} size Ukuran opsional dalam px atau em (default '1em')
 * @returns {string} Markup string SVG
 */
function renderIcon(name, className = '', size = '1em') {
  const content = ICONS[name] || ICONS['info'];
  const sizeAttr = typeof size === 'number' ? `${size}px` : size;
  return `<svg class="pos-icon ${className}" viewBox="0 0 24 24" width="${sizeAttr}" height="${sizeAttr}" fill="none" stroke="currentColor" stroke-width="1.8" stroke-linecap="round" stroke-linejoin="round" style="display:inline-block; vertical-align:middle; flex-shrink:0;">${content}</svg>`;
}

// Inisialisasi otomatis pada elemen bertanda data-icon="name"
function initIcons(root = document) {
  root.querySelectorAll('[data-icon]').forEach(el => {
    const iconName = el.getAttribute('data-icon');
    const extraClass = el.getAttribute('data-icon-class') || '';
    const size = el.getAttribute('data-icon-size') || '1em';
    el.innerHTML = renderIcon(iconName, extraClass, size);
  });
}

// Pasang event listener ripple native tablet secara global
document.addEventListener('pointerdown', (e) => {
  const target = e.target.closest('.ripple-surface, .pos-btn, .pos-chip, .pos-card-clickable, .pos-nav-item');
  if (!target || target.disabled || target.getAttribute('aria-disabled') === 'true') return;

  const rect = target.getBoundingClientRect();
  const wave = document.createElement('span');
  wave.className = 'ripple-effect';
  
  const size = Math.max(rect.width, rect.height) * 1.5;
  const x = e.clientX - rect.left - size / 2;
  const y = e.clientY - rect.top - size / 2;

  wave.style.width = `${size}px`;
  wave.style.height = `${size}px`;
  wave.style.left = `${x}px`;
  wave.style.top = `${y}px`;

  target.appendChild(wave);
  setTimeout(() => wave.remove(), 600);
});
